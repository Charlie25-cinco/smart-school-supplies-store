-- REQ-037–042: cloud store, additive to a NEW Supabase project only.
-- This migration never opens, resets, or modifies the legacy SQLite database.
begin;

create schema if not exists store_private;
revoke all on schema store_private from public, anon;

create table public.profiles (
  id bigint generated by default as identity primary key,
  auth_id uuid unique references auth.users(id) on delete restrict,
  name text not null check (length(btrim(name)) between 1 and 100),
  email text not null check (length(email) between 3 and 255),
  role text not null check (role in ('admin', 'cashier')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index profiles_email_lower_unique on public.profiles (lower(email));

create table public.devices (
  id uuid primary key,
  staff_id bigint not null references public.profiles(id) on delete restrict,
  name text not null check (length(btrim(name)) between 1 and 100),
  next_sequence bigint not null default 1 check (next_sequence > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  client_reference uuid unique,
  sku text not null unique check (sku ~ '^[A-Za-z0-9-]{1,40}$'),
  name text not null check (length(btrim(name)) between 1 and 100),
  category text not null check (length(btrim(category)) between 1 and 60),
  kind text not null check (kind in ('product', 'service', 'consumable')),
  price_cents bigint not null check (price_cents between 0 and 9999999 and (kind = 'consumable' or price_cents > 0)),
  stock bigint not null default 0 check (stock between 0 and 1000000),
  reserved bigint not null default 0 check (reserved >= 0),
  allocated bigint not null default 0 check (allocated >= 0),
  reorder_level bigint not null default 10 check (reorder_level between 0 and 1000000),
  active boolean not null default true,
  version bigint not null default 1 check (version > 0),
  price_version_id uuid,
  description text not null default '' check (length(description) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (reserved + allocated <= stock),
  check (kind <> 'service' or (stock = 0 and reserved = 0 and allocated = 0)),
  check (kind <> 'consumable' or (reserved = 0 and allocated = 0))
);

create table public.price_versions (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products(id) on delete restrict deferrable initially deferred,
  sku text not null,
  name text not null,
  kind text not null check (kind in ('product', 'service', 'consumable')),
  price_cents bigint not null check (price_cents between 0 and 9999999),
  created_at timestamptz not null default now()
);
alter table public.products add constraint products_price_version_fk foreign key (price_version_id) references public.price_versions(id) on delete restrict;
create index price_versions_product_idx on public.price_versions(product_id);

create table public.device_price_grants (
  device_id uuid not null references public.devices(id) on delete restrict,
  price_version_id uuid not null references public.price_versions(id) on delete restrict,
  granted_at timestamptz not null default now(),
  primary key (device_id, price_version_id)
);

create table public.stock_allocations (
  device_id uuid not null references public.devices(id) on delete restrict,
  product_id bigint not null references public.products(id) on delete restrict,
  price_version_id uuid not null references public.price_versions(id) on delete restrict,
  remaining bigint not null check (remaining between 0 and 1000000),
  updated_at timestamptz not null default now(),
  primary key (device_id, product_id)
);

create table public.sales (
  id bigint generated by default as identity primary key,
  reference uuid not null unique,
  receipt_number text not null unique check (length(btrim(receipt_number)) between 1 and 80),
  user_id bigint not null references public.profiles(id) on delete restrict,
  paid_by bigint not null references public.profiles(id) on delete restrict,
  channel text not null check (channel in ('walk-in', 'messenger')),
  subtotal_cents bigint not null check (subtotal_cents between 1 and 999999999),
  delivery_fee_cents bigint not null default 0 check (delivery_fee_cents between 0 and 9999999),
  total_cents bigint not null check (total_cents between 1 and 999999999 and total_cents = subtotal_cents + delivery_fee_cents),
  cash_cents bigint not null check (cash_cents between 1 and 999999999 and cash_cents >= total_cents),
  change_cents bigint not null check (change_cents >= 0),
  payment_method text not null check (payment_method in ('cash', 'gcash')),
  payment_reference text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((payment_method = 'cash' and payment_reference is null and change_cents = cash_cents - total_cents)
    or (payment_method = 'gcash' and payment_reference ~ '^[A-Z0-9-]{6,80}$' and cash_cents = total_cents and change_cents = 0))
);

create table public.orders (
  id bigint generated by default as identity primary key,
  reference uuid not null unique,
  user_id bigint not null references public.profiles(id) on delete restrict,
  assigned_cashier_id bigint references public.profiles(id) on delete restrict,
  assigned_by bigint references public.profiles(id) on delete restrict,
  assigned_at timestamptz,
  assignment_version bigint not null default 0 check (assignment_version >= 0),
  device_id uuid references public.devices(id) on delete restrict,
  sale_id bigint unique references public.sales(id) on delete restrict,
  paid_by bigint references public.profiles(id) on delete restrict,
  paid_at timestamptz,
  channel text not null check (channel in ('walk-in', 'messenger')),
  fulfillment text not null check (fulfillment in ('pickup', 'delivery')),
  payment_plan text not null check (payment_plan in ('prepaid', 'collection')),
  status text not null default 'preparing' check (status in ('preparing', 'ready', 'out_for_delivery', 'completed', 'cancelled')),
  customer_name text not null check (length(btrim(customer_name)) between 1 and 100),
  customer_phone text not null check (customer_phone ~ '^[0-9+()[:space:]-]{7,30}$'),
  delivery_address text not null default '' check (length(delivery_address) <= 300),
  notes text not null default '' check (length(notes) <= 500),
  cancel_reason text check (length(cancel_reason) <= 300),
  subtotal_cents bigint not null check (subtotal_cents between 1 and 999999999),
  delivery_fee_cents bigint not null default 0 check (delivery_fee_cents between 0 and 9999999),
  total_cents bigint not null check (total_cents between 1 and 999999999 and total_cents = subtotal_cents + delivery_fee_cents),
  version bigint not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (fulfillment <> 'delivery' or length(btrim(delivery_address)) > 0),
  check (fulfillment <> 'pickup' or (delivery_address = '' and delivery_fee_cents = 0)),
  check ((sale_id is null and paid_by is null and paid_at is null) or (sale_id is not null and paid_by is not null and paid_at is not null)),
  check (status <> 'completed' or sale_id is not null),
  check (status <> 'cancelled' or (sale_id is null and length(btrim(cancel_reason)) > 0))
);
create index orders_creator_idx on public.orders(user_id);
create index orders_assignee_idx on public.orders(assigned_cashier_id);
create index orders_device_idx on public.orders(device_id);

