create index sync_events_reviews_idx on public.sync_events(staff_id, status, created_at);

create function store_private.product_version() returns trigger
language plpgsql set search_path = pg_catalog, public as $$
declare v_price uuid;
begin
  if tg_op = 'UPDATE' and new.kind <> old.kind then
    raise exception using errcode = 'P0001', message = 'Item kind cannot be changed.';
  end if;
  if tg_op = 'INSERT' or (new.sku, new.name, new.kind, new.price_cents) is distinct from (old.sku, old.name, old.kind, old.price_cents) then
    insert into public.price_versions(product_id, sku, name, kind, price_cents)
      values (new.id, new.sku, new.name, new.kind, new.price_cents) returning id into v_price;
    new.price_version_id := v_price;
  else
    new.price_version_id := old.price_version_id;
  end if;
  if tg_op = 'UPDATE' then new.version := old.version + 1; new.updated_at := now(); end if;
  return new;
end;
$$;
create trigger products_version before insert or update on public.products for each row execute function store_private.product_version();

