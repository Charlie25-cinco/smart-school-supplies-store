create table public.sync_events (
  id uuid primary key,
  device_id uuid not null references public.devices(id) on delete restrict,
  staff_id bigint not null references public.profiles(id) on delete restrict,
  sequence bigint not null check (sequence > 0),
  kind text not null,
  request_digest text not null,
  request_identity jsonb not null,
  payload jsonb not null,
  captured_at timestamptz not null,
  status text not null check (status in ('synced', 'review')),
  message text,
  resolved_by bigint references public.profiles(id) on delete restrict,
  resolved_at timestamptz,
  resolution_note text check (length(resolution_note) <= 500),
