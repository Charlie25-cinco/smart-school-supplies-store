create table public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete restrict,
  product_id bigint not null references public.products(id) on delete restrict,
  price_version_id uuid references public.price_versions(id) on delete restrict,
  name text not null,
  sku text not null,
  kind text not null check (kind in ('product', 'service')),
  quantity bigint not null check (quantity between 1 and 999),
  price_cents bigint not null check (price_cents between 1 and 9999999),
  total_cents bigint not null check (total_cents = price_cents * quantity),
  unique (sale_id, product_id)
);

create table public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  user_id bigint references public.profiles(id) on delete restrict,
  sale_id bigint references public.sales(id) on delete restrict,
  quantity bigint not null check (quantity <> 0 and abs(quantity) <= 1000000),
  reason text not null check (length(btrim(reason)) between 1 and 200),
